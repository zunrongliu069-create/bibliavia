const chapterOneVerses = (
  translationId: string,
  bookId: Verse['bookId'],
  bookName: string,
  languageTag: string,
  sourceUrl: string,
  texts: string[],
): Verse[] =>
  texts.map((text, index) => {
    const verse = index + 1;
    return {
      id: `${translationId}-${bookId}-${verse}`,
      translationId,
      bookId,
      bookName,
      chapter: 1,
      verseStart: verse,
      verseEnd: verse,
      reference: `${bookName} 1:${verse}`,
      languageTag,
      text,
      sourceUrl,
    };
  });

